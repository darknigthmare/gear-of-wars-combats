import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require=createRequire(path.join(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES,'package.json'));
const {chromium}=require('playwright');
const dir=path.dirname(fileURLToPath(import.meta.url));
await fs.mkdir(path.join(dir,'qa'),{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:1080}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('file://'+path.join(dir,'Gears_Combats_Prototype.html'));
await page.waitForFunction(()=>['marcus','raam','stage'].every(key=>window.GearsPrototype?.assets[key]?.complete));
const embeddedAssets=await page.evaluate(()=>Object.keys(window.GEARS_ASSETS).sort());
assert.deepEqual(embeddedAssets,['marcus','raam','stage']);
assert.equal(await page.locator('#menu').isVisible(),true);
await page.screenshot({path:path.join(dir,'qa','desktop-menu.png'),fullPage:true});
await page.click('#start-btn');
await page.keyboard.down('l');await page.waitForTimeout(380);await page.keyboard.up('l');
const ammo=await page.evaluate(()=>window.GearsPrototype.getState().player.ammo);assert(ammo<8);
await page.keyboard.press('r');
assert(await page.evaluate(()=>!!window.GearsPrototype.getState().player.reload));
await page.click('#pause-btn');
assert(await page.evaluate(()=>window.GearsPrototype.getState().paused));
const pausedTime=await page.evaluate(()=>window.GearsPrototype.getState().time);await page.waitForTimeout(120);
assert.equal(await page.evaluate(()=>window.GearsPrototype.getState().time),pausedTime);
await page.click('#resume-btn');
await page.screenshot({path:path.join(dir,'qa','desktop-duel.png'),fullPage:true});
await page.click('#menu-btn');await page.click('[data-mode="berserker"]');await page.click('#start-btn');
await page.evaluate(()=>{const g=window.GearsPrototype.getState();g.enemy.hp=800;g.enemy.clock=1;});
await page.waitForTimeout(40);assert.equal(await page.evaluate(()=>window.GearsPrototype.getState().enemy.phase),3);
await page.screenshot({path:path.join(dir,'qa','desktop-berserker.png'),fullPage:true});
await page.click('#menu-btn');await page.click('[data-mode="raven"]');await page.click('#start-btn');
await page.evaluate(()=>{const g=window.GearsPrototype.getState();g.enemy.hp=500;g.enemy.clock=1;});
await page.waitForTimeout(40);assert.equal(await page.evaluate(()=>window.GearsPrototype.getState().zones.length),3);
await page.screenshot({path:path.join(dir,'qa','desktop-raven.png'),fullPage:true});
await page.evaluate(()=>window.GearsPrototype.getState().enemy.hp=0);await page.waitForTimeout(40);assert.equal(await page.locator('#result').isVisible(),true);
assert.equal(await page.locator('#result-title').innerText(),'VICTOIRE.');
await page.click('#retry-btn');assert.equal(await page.locator('#result').isVisible(),false);
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
mobile.on('pageerror',e=>errors.push(e.message));await mobile.goto('file://'+path.join(dir,'Gears_Combats_Prototype.html'));
assert.equal(await mobile.locator('.touch').isVisible(),true);assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
await mobile.screenshot({path:path.join(dir,'qa','mobile-menu.png'),fullPage:true});
await mobile.tap('#start-btn');const before=await mobile.evaluate(()=>window.GearsPrototype.getState().player.ammo);
await mobile.tap('[data-action="shoot"]');await mobile.waitForTimeout(80);
const after=await mobile.evaluate(()=>window.GearsPrototype.getState().player.ammo);
assert(after<before,'Touch tap fires at least one shot');
await mobile.screenshot({path:path.join(dir,'qa','mobile-combat.png'),fullPage:true});
assert.deepEqual(errors,[]);
await browser.close();
const summary={date:'2026-11-20',desktop:'Menu, duel firing, reload, pause, 3 boss phases, vehicle zones, victory and restart verified',mobile:'390×844 layout without horizontal overflow and touch firing verified',pageErrors:errors,embeddedAssets,hardwareGamepad:'Not tested on physical hardware'};
await fs.writeFile(path.join(dir,'qa','browser-report-v5.json'),JSON.stringify(summary,null,2));console.log(JSON.stringify(summary,null,2));
